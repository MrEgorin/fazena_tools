def dock_single_compound(
    receptor_pdb: str,
    ligand_smiles: str,
    compound_name: str = "Compound",
    grid_box: Optional[Dict[str, float]] = None,
    exhaustiveness: int = 8,
    n_poses: int = 3,
    is_rna: bool = False
) -> Dict[str, Any]:
    """
    Executes AutoDock Vina docking for a single ligand against a receptor.
    Returns affinities, Ki, docked pose PDBQT, and merged complex PDB.
    """
    if grid_box is None:
        grid_box = calculate_grid_box(receptor_pdb)

    lig_pdbqt, lig_mol_3d = prepare_ligand_pdbqt(ligand_smiles)
    if not lig_pdbqt:
        return {'status': 'Failed', 'error': 'Could not prepare ligand 3D structure'}

    rec_pdbqt = prepare_receptor_pdbqt(receptor_pdb, is_rna=is_rna)
    if not rec_pdbqt:
        return {'status': 'Failed', 'error': 'Could not prepare receptor PDBQT'}

    with tempfile.TemporaryDirectory() as tmpdir:
        rec_file = os.path.join(tmpdir, "receptor.pdbqt")
        with open(rec_file, "w") as f:
            f.write(rec_pdbqt)

        try:
            cpu_count = min(os.cpu_count() or 4, 8)
            v = Vina(sf_name='vina', cpu=cpu_count, verbosity=0)
            v.set_receptor(rec_file)
            v.set_ligand_from_string(lig_pdbqt)

            center = [grid_box['center_x'], grid_box['center_y'], grid_box['center_z']]
            box_size = [grid_box['size_x'], grid_box['size_y'], grid_box['size_z']]
            v.compute_vina_maps(center=center, box_size=box_size)

            v.dock(exhaustiveness=exhaustiveness, n_poses=n_poses)
            energies = v.energies(n_poses=n_poses)
            poses_pdbqt = v.poses(n_poses=n_poses)

            best_affinity = round(float(energies[0][0]), 2)
            # Estimated Ki: Ki = exp(deltaG / (R * T))
            r_const = 1.9872e-3
            temp = 298.15
            ki_molar = math.exp(best_affinity / (r_const * temp))
            if ki_molar < 1e-6:
                ki_str = f"{ki_molar * 1e9:.2f} nM"
            elif ki_molar < 1e-3:
                ki_str = f"{ki_molar * 1e6:.2f} µM"
            else:
                ki_str = f"{ki_molar * 1e3:.2f} mM"

            top_pose_pdbqt = poses_pdbqt.split("ENDMDL")[0] + "\nENDMDL\n"
            top_pose_pdb = convert_pose_pdbqt_to_pdb(top_pose_pdbqt)

            # Assemble merged complex PDB
            clean_rec_lines = [l for l in receptor_pdb.splitlines() if not l.startswith(('END', 'CONECT'))]
            clean_lig_lines = [l for l in top_pose_pdb.splitlines() if l.startswith(('ATOM', 'HETATM'))]
            complex_pdb = "\n".join(clean_rec_lines) + "\n" + "\n".join(clean_lig_lines) + "\nEND\n"

            return {
                'status': 'Success',
                'name': compound_name,
                'SMILES': ligand_smiles,
                'affinity': best_affinity,
                'ki_estimated': ki_str,
                'energies_all': [round(float(e[0]), 2) for e in energies],
                'top_pose_pdbqt': top_pose_pdbqt,
                'top_pose_pdb': top_pose_pdb,
                'complex_pdb': complex_pdb,
                'grid_box': grid_box
            }
        except Exception as e:
            return {'status': 'Failed', 'error': str(e)}

def dock_top_candidates(
    receptor_pdb: str,
    candidates: List[Dict[str, Any]],
    top_n: int = 5,
    is_rna: bool = False,
    progress_callback = None
) -> List[Dict[str, Any]]:
    """Docks the top N candidate compounds from virtual screening results."""
    results = []
    candidates_to_dock = candidates[:top_n]
    grid_box = calculate_grid_box(receptor_pdb)

    for i, cand in enumerate(candidates_to_dock):
        smiles = cand.get('SMILES', '')
        name = cand.get('name', f"Hit_{i+1}")

        if progress_callback:
            progress_callback(i + 1, len(candidates_to_dock), name)

        dock_res = dock_single_compound(
            receptor_pdb=receptor_pdb,
            ligand_smiles=smiles,
            compound_name=name,
            grid_box=grid_box,
            exhaustiveness=6,
            n_poses=3,
            is_rna=is_rna
        )
        dock_res.update({k: v for k, v in cand.items() if k not in dock_res})
        results.append(dock_res)

    successful = [r for r in results if r.get('status') == 'Success']
    failed = [r for r in results if r.get('status') != 'Success']
    successful.sort(key=lambda x: x.get('affinity', 999.0))
    return successful + failed

